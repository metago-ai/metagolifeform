/** 简单可复现 PRNG（mulberry32） */
export function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** 铜钱法起卦：seed 可复现；返回 6 爻（0/1）与动爻索引 */
export function coinDivination(seed) {
  const rand = mulberry32(seed);
  const lines = [];
  const moving = [];
  for (let i = 0; i < 6; i++) {
    const sum = Math.floor(rand() * 3) + Math.floor(rand() * 3) + Math.floor(rand() * 3);
    // 三枚铜钱：字=2 背=3。6=老阴(动)，7=少阳，8=少阴，9=老阳(动)
    const value = sum + 3; // 3..9 映射
    const v = value === 6 ? 0 : value === 7 ? 1 : value === 8 ? 0 : 1;
    lines.push(v);
    if (value === 6 || value === 9) moving.push(i);
  }
  return { lines, moving };
}

/** 时间法起卦：日期+时辰 → seed（确定性） */
export function timeSeed(y, m, d, hour) {
  return (y * 10000 + m * 100 + d) * 100 + Math.floor(((hour + 1) % 24) / 2);
}

/** 变卦：动爻翻转 */
export function changeGua(lines, moving) {
  const out = [...lines];
  for (const i of moving) out[i] = out[i] === 1 ? 0 : 1;
  return out;
}

/** 互卦：2-5 爻（二三四为下互，三四五为上互） */
export function huGua(lines) {
  return [lines[1], lines[2], lines[3], lines[2], lines[3], lines[4]];
}

/** 错卦：阴阳全反 */
export function cuoGua(lines) {
  return lines.map(l => (l === 1 ? 0 : 1));
}

/** 综卦：上下倒置 */
export function zongGua(lines) {
  return [...lines].reverse();
}

/** 爻辞：卦名（通行本单字名）+ 爻位 → 爻辞正文 */
export function yaoCi(guaShortName, yaoIdx) {
  const list = YAOCI_ALL[guaShortName];
  if (!list) return null;
  return list[yaoIdx] ?? null;
}

/** 完整推演：起卦 → 本卦/变卦/互卦/错卦/综卦 */
export function divine(seed, opts = {}) {
  const { lines, moving } = opts.lines ? { lines: opts.lines, moving: opts.moving || [] } : coinDivination(seed);
  const ben = lines;
  const bian = changeGua(ben, moving);
  const hu = huGua(ben);
  const cuo = cuoGua(ben);
  const zong = zongGua(ben);
  const nameOf = (six) => {
    const lower = six.slice(0, 3), upper = six.slice(3);
    return guaNameByLines(upper, lower);
  };
  const benName = nameOf(ben);
  const bianName = nameOf(bian);
  const benShort = benName ? Object.keys(GUA_FULL).find(k => GUA_FULL[k] === benName) : null;
  return {
    seed,
    ben: {
      name: benName, lines: ben,
      guaCi: benShort ? GUA_CI[benShort] : null,
      yaoCi: benShort ? ben.map((_, i) => yaoCi(benShort, i)) : null
    },
    bian: { name: bianName, lines: bian },
    hu: { name: nameOf(hu), lines: hu },
    cuo: { name: nameOf(cuo), lines: cuo },
    zong: { name: nameOf(zong), lines: zong },
    moving,
    movingTitles: moving.map(i => yaoTitle(i, ben[i]))
  };
}
