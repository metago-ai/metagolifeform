/** 由上下经卦推卦名（查 GUA_LINES） */
export function guaNameByLines(upper, lower) {
  const key = JSON.stringify([upper, lower]);
  for (const [name, lines] of Object.entries(GUA_LINES)) {
    if (JSON.stringify(lines) === key) return name;
  }
  return null;
}

/** 六爻卦 = 自下而上 6 爻 [初,二,三,四,五,上]（1=阳 0=阴） */
export function sixLines(fullName) {
  const [upper, lower] = GUA_LINES[fullName];
  return [...lower, ...upper];
}

/** 六爻卦 → 上下经卦名 */
export function guaParts(fullName) {
  const [upper, lower] = GUA_LINES[fullName];
  const up = Object.keys(JING_GUA).find(k => JSON.stringify(JING_GUA[k].lines) === JSON.stringify(upper));
  const lo = Object.keys(JING_GUA).find(k => JSON.stringify(JING_GUA[k].lines) === JSON.stringify(lower));
  return { upper: up, lower: lo };
}

/** 爻题：初/二/三/四/五/上 + 九/六 */
export function yaoTitle(idx, line) {
  const pos = ['初', '二', '三', '四', '五', '上'][idx];
  const gy = line === 1 ? '九' : '六';
  return idx === 0 ? `${pos}${gy}` : idx === 5 ? `${pos}${gy}` : `${gy}${pos}`;
}

