function searchConcepts(keywords) {
    const lowerKeywords = keywords.map(k => k.toLowerCase());
    return exports.CONCEPTS.filter(c => c.keywords.some(k => lowerKeywords.some(lk => k.toLowerCase().includes(lk))) ||
        lowerKeywords.some(lk => c.name.toLowerCase().includes(lk) || c.description.toLowerCase().includes(lk)));
}
